// Packs pdf.js for the Android PDF viewer: node scripts/vendor-pdfjs.mjs <unpacked pdfjs-dist>
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { gzipSync } from "node:zlib";

const from = process.argv[2];
if (!from) throw new Error("Usage: node scripts/vendor-pdfjs.mjs <unpacked pdfjs-dist>");

// The legacy build also runs on older Android web views. Fonts and CMaps stay out: they come to 2.4 MB and are rarely needed.
const PARTS = {
  lib: "legacy/build/pdf.min.mjs",
  worker: "legacy/build/pdf.worker.min.mjs",
  "jbig2.wasm": "wasm/jbig2.wasm",
  "openjpeg.wasm": "wasm/openjpeg.wasm",
};

const { version, license } = JSON.parse(readFileSync(path.join(from, "package.json"), "utf8"));
const lines = Object.entries(PARTS).map(([name, file]) => {
  const packed = gzipSync(readFileSync(path.join(from, file)), { level: 9 }).toString("base64");
  return `  ${JSON.stringify(name)}: "${packed}",`;
});
const target = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../src/lib/pdfjs-code.android.ts");
writeFileSync(target, `/** Generated by scripts/vendor-pdfjs.mjs from pdfjs-dist ${version} (${license}), gzip and base64. */\nexport const PDFJS_PARTS: Record<string, string> = {\n${lines.join("\n")}\n};\n`);
